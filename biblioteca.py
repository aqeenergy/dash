"""biblioteca.py — the PSI database as a browsable TEXT library.

Reads base_de_datos/ strictly READ-ONLY and writes text renderings to static/library/ (served by
Streamlit at /app/static/library/), so the web can preview any database file and the AI's
citations can open the exact local file instead of an online NASA page.

  PSI-XX.json            -> PSI-XX.md      readable investigation record (title, DOI, objective,
                                            approach, hypothesis, hardware, dates, people,
                                            publications, file list). The raw JSON is mostly
                                            download bookkeeping (up to 8 MB), so it is summarised.
  *.csv / *.tsv          -> same text, re-encoded to UTF-8 (rendered as a table in the web)
  *.xlsx / *.xls         -> one CSV per sheet  (<name>__<sheet>.csv)
  _todas_las_...json     -> catalogue of all PSI investigations (.md)
  *.md / *.py / other    -> copied as text

Derived files generated by psi_database.py (they now live in knowledge_cache/) are left out:
the library shows the team's database, not app caches.

index.json = manifest: [{id, file, label, kind, acc, investigation, size, rows, cols, url, sheet}]
"""
from __future__ import annotations

import csv
import io
import json
import re
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DB_DIR = ROOT / "base_de_datos"          # READ-ONLY
OUT_DIR = ROOT / "static" / "library"    # derived text library
URL = "app/static/library/"  # relative (Streamlit Cloud serves under /~/+/)
VERSION = 5                              # bump to force a rebuild after format changes

DERIVED = {"class_notes.json", "experiments.json", "fire_response.json", "knowledge_build_info.json",
           "materials.json", "mission_presets.json", "psi_index.json", "rules.json", "sources.json"}


def _slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name).strip("_")


def _read_text(path: Path) -> str:
    raw = path.read_bytes()
    for enc in ("utf-8-sig", "cp1252", "latin-1"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")


def _acc(name: str) -> str:
    m = re.match(r"(PSI-\d+)", name)
    return m.group(1) if m else ""


def _date(v) -> str:
    if isinstance(v, dict) and "$date" in v:
        v = v["$date"]
    try:
        x = float(v)
        if x > 1e11:
            x /= 1000
        return datetime.fromtimestamp(x, tz=timezone.utc).strftime("%Y-%m-%d")
    except (TypeError, ValueError):
        return str(v or "")


def _ficha_md(d: dict, filename: str) -> str:
    acc = d.get("accession", _acc(filename))
    acr = d.get("investigationAcronym") or ""
    lines = [f"# {acc}{' · ' + acr if acr else ''} — {d.get('title', '')}", ""]
    meta = [
        ("Accession", acc), ("Acronym", acr),
        ("DOI", d.get("doi")), ("Project title", d.get("projectTitle")),
        ("Research area", d.get("researchArea")), ("Sub-area", d.get("subResearchArea")),
        ("Hardware", d.get("experimentHardware")), ("Flight program", d.get("flightProgram")),
        ("Mission", d.get("missionName")), ("Managing center", d.get("managingNasaCenter")),
        ("Investigation dates", " – ".join(x for x in (_date(d.get("investigationStartDate")), _date(d.get("investigationEndDate"))) if x)),
        ("License", d.get("licenseName")),
    ]
    for k, v in meta:
        if v not in (None, "", [], {}):
            lines.append(f"- **{k}:** {v}")
    for title, key in (("Objective", "objective"), ("Approach", "approach"), ("Hypothesis", "hypothesis"),
                       ("Description", "description"), ("Research impacts", "researchImpacts")):
        txt = str(d.get(key) or "").strip()
        if txt:
            lines += ["", f"## {title}", "", txt]
    people = []
    for c in d.get("contacts") or []:
        if not isinstance(c, dict):
            continue
        name = " ".join(x for x in (c.get("firstName"), c.get("lastName")) if x)
        roles = ", ".join(r.get("annotationValue", "") for r in c.get("roles") or [] if isinstance(r, dict))
        aff = c.get("affiliation") or ""
        if name:
            people.append(f"- {name}" + (f" — {roles}" if roles else "") + (f" ({aff})" if aff else ""))
    if people:
        lines += ["", "## People", ""] + people
    pubs = []
    for p in d.get("publications") or []:
        if isinstance(p, dict):
            t = p.get("title") or ""
            a = p.get("authorList") or ""
            doi = p.get("doi") or ""
            if t:
                pubs.append(f"- {t}" + (f" — {a}" if a else "") + (f" (DOI {doi})" if doi else ""))
    if pubs:
        lines += ["", f"## Publications ({len(pubs)})", ""] + pubs
    files = []
    for key, label in (("experimentalTable", "Experimental table"), ("added", "Repository file")):
        for f in d.get(key) or []:
            if isinstance(f, dict) and f.get("file_name"):
                files.append(f"- {label}: {f['file_name']}")
    if files:
        lines += ["", f"## Files listed in the record ({len(files)})", ""] + files[:80]
        if len(files) > 80:
            lines.append(f"- … and {len(files) - 80} more")
    lines += ["", f"_Readable rendering of `base_de_datos/{filename}` (raw record: download bookkeeping omitted)._"]
    return "\n".join(lines)


def _catalog_md(d: dict) -> str:
    hits = (d.get("hits") or {}).get("hits") or []
    rows = []
    for h in hits:
        s = h.get("_source") or {}
        rows.append((s.get("Accession", ""), s.get("Acronym", ""), s.get("Title", ""), s.get("Research Area", "")))
    rows.sort(key=lambda r: int(re.sub(r"\D", "", r[0]) or 0))
    out = [f"# All NASA PSI investigations ({len(rows)})", "", "| Accession | Acronym | Title | Research area |", "|---|---|---|---|"]
    out += [f"| {a} | {b} | {c.replace('|', '/')} | {r} |" for a, b, c, r in rows]
    out += ["", "_Rendering of `base_de_datos/_todas_las_investigaciones_PSI.json`._"]
    return "\n".join(out)


CATALOG_FIELDS = (("Objectives", "Objective"), ("Hypothesis", "Hypothesis"), ("Approach", "Approach"),
                  ("Research Impacts/Earth Benefits", "Research impacts"))


def catalog_record_md(src: dict) -> str:
    """Readable record for one entry of _todas_las_investigaciones_PSI.json (shared with the theory engine)."""
    acc, acr = str(src.get("Accession") or ""), str(src.get("Acronym") or "").strip()
    lines = [f"# {acc}{' · ' + acr if acr else ''} — {str(src.get('Title') or '').strip()}", ""]
    for k, label in (("Research Area", "Research area"), ("SubResearch Area", "Sub-area"),
                     ("Experiment Hardware", "Hardware"), ("Flight Platform", "Flight platform"),
                     ("Project Type", "Project type"), ("Related Investigations", "Related investigations")):
        v = " ".join(str(src.get(k) or "").split())
        if v.startswith("{") or v.startswith("["):  # structured catalogue values, e.g. {'Name': '', 'Link': ''}
            import ast
            try:
                obj = ast.literal_eval(v)
                items = obj if isinstance(obj, list) else [obj]
                v = ", ".join(str(i.get("Name") or i.get("Accession") or "").strip() if isinstance(i, dict) else str(i) for i in items)
                v = ", ".join(x for x in v.split(", ") if x)
            except Exception:
                pass
        if v:
            lines.append(f"- **{label}:** {v}")
    kw = " · ".join(x.strip() for x in re.split(r"\s{3,}", str(src.get("Keywords") or "")) if x.strip())
    if kw:
        lines.append(f"- **Keywords:** {kw}")
    for key, label in CATALOG_FIELDS:
        v = str(src.get(key) or "").strip()
        if v:
            lines += ["", f"## {label}", "", v]
    pubs = [x.strip() for x in re.split(r"\s{3,}", str(src.get("Publication Title") or "")) if x.strip()]
    if pubs:
        lines += ["", f"## Publications ({len(pubs)})", ""] + [f"- {p}" for p in pubs[:40]]
    lines += ["", "_Rendering of this investigation's entry in `base_de_datos/_todas_las_investigaciones_PSI.json`._"]
    return "\n".join(lines)


def _csv_stats(text: str) -> tuple[int, int]:
    try:
        rows = list(csv.reader(io.StringIO(text)))
    except Exception:
        return 0, 0
    rows = [r for r in rows if any(c.strip() for c in r)]
    return max(len(rows) - 1, 0), (len(rows[0]) if rows else 0)


def _source_mtime() -> float:
    return max([Path(__file__).stat().st_mtime] + [p.stat().st_mtime for p in DB_DIR.iterdir() if p.is_file()])


def build(force: bool = False) -> list[dict]:
    manifest_path = OUT_DIR / "index.json"
    if not force and manifest_path.exists() and manifest_path.stat().st_mtime >= _source_mtime():
        try:
            data = json.loads(manifest_path.read_text(encoding="utf-8"))
            if data.get("version") == VERSION:
                return data["files"]
        except Exception:
            pass
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.iterdir():
        if old.is_file():
            old.unlink()
    titles = {}
    for p in DB_DIR.glob("PSI-*.json"):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
            titles[p.stem] = (d.get("investigationAcronym") or "", d.get("title") or "")
        except Exception:
            pass

    entries: list[dict] = []

    def add(src: Path, out_name: str, text: str, kind: str, label: str, **extra) -> None:
        (OUT_DIR / out_name).write_text(text, encoding="utf-8", newline="\n")
        acc = _acc(src.name)
        acr, title = titles.get(acc, ("", ""))
        entries.append({"id": out_name, "file": src.name, "label": label, "kind": kind, "acc": acc,
                        "investigation": acr or (acc if acc else "General"), "title": title,
                        "size": src.stat().st_size, "url": URL + out_name, **extra})

    for src in sorted(DB_DIR.iterdir(), key=lambda p: (int(re.sub(r"\D", "", _acc(p.name)) or 10**6), p.name)):
        if not src.is_file() or src.name in DERIVED:
            continue
        name, suf = src.name, src.suffix.lower()
        try:
            if re.fullmatch(r"PSI-\d+\.json", name):
                add(src, _slug(src.stem) + ".md", _ficha_md(json.loads(src.read_text(encoding="utf-8")), name),
                    "record", "Investigation record")
            elif name.startswith("_todas") and suf == ".json":
                add(src, "catalog.md", _catalog_md(json.loads(src.read_text(encoding="utf-8"))), "catalog",
                    "Catalogue of all PSI investigations")
            elif suf in (".csv", ".tsv"):
                text = _read_text(src)
                if suf == ".tsv":
                    text = "\n".join(",".join(f'"{c}"' if "," in c else c for c in line.split("\t")) for line in text.splitlines())
                rows, cols = _csv_stats(text)
                kind = "table" if "Experimental table" in name else "log"
                label = re.sub(r"^PSI-\d+_", "", src.stem).replace("_", " · ") if kind == "table" else "Download log"
                add(src, _slug(src.stem) + ".csv", text, kind, label, rows=rows, cols=cols)
            elif suf in (".xlsx", ".xls"):
                import pandas as pd
                sheets = pd.read_excel(src, sheet_name=None, header=None)
                for sheet, df in sheets.items():
                    df = df.dropna(how="all").dropna(axis=1, how="all")
                    text = df.to_csv(index=False, header=False)
                    rows, cols = _csv_stats(text)
                    add(src, _slug(src.stem) + "__" + _slug(str(sheet)) + ".csv", text, "workbook",
                        re.sub(r"^PSI-\d+_", "", src.stem).replace("_", " · ") + f" — sheet “{sheet}”",
                        rows=rows + 1, cols=cols, sheet=str(sheet))
            else:  # .md, .py, other text
                add(src, _slug(name) + ".txt", _read_text(src), "doc",
                    "Team guide to the PSI data" if suf == ".md" else "Curated experiment list")
        except Exception as e:  # never break the app because one file is odd
            add(src, _slug(name) + ".txt", f"Could not render this file as text: {e}", "doc", "Unreadable file")

    # Every other PSI investigation (non-combustion areas) as a readable record from the catalogue,
    # so AI theories can cite and open any of the 133 investigations locally.
    catalog = DB_DIR / "_todas_las_investigaciones_PSI.json"
    if catalog.exists():
        for h in (json.loads(catalog.read_text(encoding="utf-8")).get("hits") or {}).get("hits") or []:
            src_ = h.get("_source") or {}
            acc = str(src_.get("Accession") or "")
            if not acc or (DB_DIR / f"{acc}.json").exists():
                continue
            text = catalog_record_md(src_)
            out_name = _slug(acc) + ".md"
            (OUT_DIR / out_name).write_text(text, encoding="utf-8", newline="\n")
            entries.append({"id": out_name, "file": catalog.name, "label": "Investigation record (catalogue entry)",
                            "kind": "record", "acc": acc, "investigation": str(src_.get("Acronym") or "").strip() or acc,
                            "title": str(src_.get("Title") or "").strip(), "size": len(text.encode("utf-8")),
                            "url": URL + out_name, "area": src_.get("Research Area", "")})
    manifest_path.write_text(json.dumps({"version": VERSION, "files": entries}, ensure_ascii=False), encoding="utf-8")
    return entries


def file_for_table(table_stem: str) -> str | None:
    """Library id of an experimental table, from its file stem (as used in AI citations)."""
    for e in build():
        if Path(e["file"]).stem == table_stem and e["kind"] == "table":
            return e["id"]
    return None


if __name__ == "__main__":
    import sys
    files = build(force="--force" in sys.argv)
    kinds = {}
    for e in files:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
    print(len(files), "library entries:", kinds)
    for e in files[:8]:
        print(" ", e["id"], "|", e["label"], "|", e.get("rows"), "rows")
